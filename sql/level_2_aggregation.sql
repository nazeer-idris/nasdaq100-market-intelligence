-- Calculate the average inflation rate using CPI values
SELECT
	AVG(INFLATION_CPI) AS AVERAGE_INFLATION_CPI
FROM
	MACRO_ECONOMIC_INDICATORS;


-- Count how many days the gold price closed above $1800
SELECT
	COUNT(*) AS COUNT_CLOSE_PRICE_ABOVE_1800
FROM
	GOLD
WHERE
	CLOSE_VALUE > 1800


-- Find days with significant daily range (high - low) in NASDAQ 100
SELECT
	DATE_VALUE,
	SUM(HIGH_VALUE - LOW_VALUE) AS TOTAL_DAILY_RANGE
FROM
	PUBLIC.NASDAQ_100_DAILY
GROUP BY
	DATE_VALUE
ORDER BY
	TOTAL_DAILY_RANGE DESC
LIMIT
	10;


-- Find the top 5 stocks with the highest daily price changes
SELECT
	COMPANY_PREFIX,
	MAX(HIGH_VALUE - LOW_VALUE) AS MAX_DAILY_CHANGE
FROM
	PUBLIC.NASDAQ_100_DAILY
GROUP BY
	COMPANY_PREFIX
ORDER BY
	MAX_DAILY_CHANGE DESC
LIMIT
	5;